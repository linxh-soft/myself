def _int_list(value, label, min_size=1):
    if not isinstance(value, list) or len(value) < min_size:
        raise RuntimeError(f"{label} must be a JSON array with at least {min_size} atom indices")
    try:
        result = [int(x) for x in value]
    except (TypeError, ValueError) as exc:
        raise RuntimeError(f"{label} contains a non-integer atom index") from exc
    if len(result) != len(set(result)) or min(result) < 1:
        raise RuntimeError(f"{label} atom indices must be unique positive integers")
    return result


def apply_system_config(path):
    """Apply a JSON system description while retaining legacy defaults."""
    global FILES, REFERENCE, FE_INDEX, LIG_START, LIG_END, REACTIVE_O, SUB_START
    global LIGAND_INDICES, SUBSTRATE_INDICES, REACTION_SITE_REF, REACTION_SITE_LABELS
    global SUBSTRATE_PLANE_REF, LIGAND_PLANE_REFS, LOCAL_FRAGMENT_REF
    global LOCAL_FRAGMENT_RADIUS, CATALYST_CORE_REF, STRUCTURE_METADATA

    with open(path, encoding="utf-8") as f:
        cfg = json.load(f)
    if not isinstance(cfg, dict):
        raise RuntimeError("System config root must be a JSON object")

    if "files" in cfg:
        if not isinstance(cfg["files"], dict) or not cfg["files"]:
            raise RuntimeError("files must be a non-empty name-to-XYZ JSON object")
        FILES = {str(k): str(v) for k, v in cfg["files"].items()}
    STRUCTURE_METADATA = cfg.get("structure_metadata", {})
    if not isinstance(STRUCTURE_METADATA, dict):
        raise RuntimeError("structure_metadata must be a name-to-metadata object")
    REFERENCE = str(cfg.get("reference", REFERENCE))
    if REFERENCE not in FILES:
        raise RuntimeError(f"Configured reference {REFERENCE!r} is not present in files")

    fragments = cfg.get("fragments", {})
    if "metal" in fragments:
        metal = _int_list(fragments["metal"], "fragments.metal", 1)
        if len(metal) != 1:
            raise RuntimeError("This analysis currently supports exactly one metal center")
        FE_INDEX = metal[0]
    if "ligand" in fragments:
        LIGAND_INDICES = set(_int_list(fragments["ligand"], "fragments.ligand"))
        LIG_START, LIG_END = min(LIGAND_INDICES), max(LIGAND_INDICES)
    if "substrate" in fragments:
        SUBSTRATE_INDICES = set(_int_list(fragments["substrate"], "fragments.substrate"))
        SUB_START = min(SUBSTRATE_INDICES)
    if "reactive_atoms" in fragments:
        reactive = _int_list(fragments["reactive_atoms"], "fragments.reactive_atoms", 2)
        if len(reactive) != 2:
            raise RuntimeError("fragments.reactive_atoms must contain exactly two atoms")
        REACTIVE_O = tuple(reactive)

    reaction = cfg.get("reaction", {})
    if "substrate_sites" in reaction:
        sites = reaction["substrate_sites"]
        if not isinstance(sites, list) or len(sites) != 2:
            raise RuntimeError("reaction.substrate_sites must contain exactly two objects")
        REACTION_SITE_REF = tuple(int(x["atom"]) for x in sites)
        REACTION_SITE_LABELS = tuple(str(x.get("label", f"site_{i + 1}")) for i, x in enumerate(sites))

    descriptors = cfg.get("descriptors", {})
    plane = descriptors.get("substrate_plane")
    if plane is not None:
        SUBSTRATE_PLANE_REF = tuple(_int_list(plane, "descriptors.substrate_plane", 3))
    ligand_planes = descriptors.get("ligand_planes")
    if ligand_planes is not None:
        if not isinstance(ligand_planes, dict) or not ligand_planes:
            raise RuntimeError("descriptors.ligand_planes must be a non-empty name-to-atoms object")
        LIGAND_PLANE_REFS = {
            str(name): tuple(_int_list(ids, f"descriptors.ligand_planes.{name}", 3))
            for name, ids in ligand_planes.items()
        }
    local = descriptors.get("local_fragment", {})
    if "atoms" in local:
        LOCAL_FRAGMENT_REF = tuple(_int_list(local["atoms"], "descriptors.local_fragment.atoms", 1))
    if "graph_radius" in local:
        LOCAL_FRAGMENT_RADIUS = int(local["graph_radius"])
        if LOCAL_FRAGMENT_RADIUS < 0:
            raise RuntimeError("descriptors.local_fragment.graph_radius cannot be negative")
    if "catalyst_core" in descriptors:
        CATALYST_CORE_REF = tuple(_int_list(descriptors["catalyst_core"], "descriptors.catalyst_core", 3))

    return cfg


