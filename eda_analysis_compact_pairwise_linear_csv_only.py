def to_float(cell):
    if cell is None:
        return None
    t = str(cell).strip()
    if not t:
        return None
    t = t.replace("−", "-").replace("–", "-").replace("—", "-").replace(",", "")
    m = re.search(r"[-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?", t)
    if not m:
        return None
    try:
        return float(m.group(0))
    except ValueError:
        return None


