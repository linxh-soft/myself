def select_linear_relationships(correlation_rows, min_abs_r=0.90, min_r2=0.80, min_n=5):
    """Select strong structure-level descriptor-EDA relationships.

    Pairwise correlations are intentionally excluded here because they are not
    independent observations.
    """
    selected = []
    for row in correlation_rows:
        if row.get("correlation_mode") != "structure_level":
            continue
        r = to_float(row.get("Pearson_r"))
        r2 = to_float(row.get("R2"))
        n = int(row.get("n", 0))
        if r is None or r2 is None:
            continue
        if abs(r) >= min_abs_r and r2 >= min_r2 and n >= min_n:
            row = dict(row)
            row["linear_strength"] = abs(r) * r2
            if row.get("mechanistic_relevance", "").startswith(("targeted", "plausible")):
                row["confidence"] = "high"
            else:
                row["confidence"] = "exploratory"
            loo = [to_float(row.get("r_min_leave_one_out")), to_float(row.get("r_max_leave_one_out"))]
            valid_loo = [x for x in loo if x is not None]
            if valid_loo and all(x * r > 0 and abs(x) >= 0.70 for x in valid_loo):
                row["robustness"] = "robust"
            elif valid_loo:
                row["robustness"] = "sensitive"
            else:
                row["robustness"] = "not_assessed"
            selected.append(row)

    selected.sort(key=lambda x: (-x["linear_strength"], -abs(float(x["Pearson_r"]))))
    for i, row in enumerate(selected, start=1):
        row["rank"] = i
    return selected


def plot_selected_linear_relationships(selected_rows, model_rows, eda_data, outdir):
    """Write plot-ready long data and one CSV per selected relationship."""
    table_dir = Path(outdir) / "linear_relationship_tables"
    table_dir.mkdir(parents=True, exist_ok=True)
    model = {r["structure"]: r for r in model_rows}
    combined = []
    for row in selected_rows:
        descriptor = row["descriptor"]
        eda = row["EDA_term"]
        names = [n for n in str(row.get("data_ids", "")).split(";") if n]
        relationship_id = f"R{int(row['rank']):03d}"
        points = []
        for n in names:
            if n not in model:
                continue
            xv = model[n].get(descriptor)
            yv = eda_data.get(n, {}).get(eda)
            x = to_float(xv)
            y = to_float(yv)
            if x is None or y is None:
                continue
            fitted = float(row["slope"]) * x + float(row["intercept"])
            point_row = {
                "relationship_id": relationship_id, "rank": row["rank"],
                "subset": row["subset"], "descriptor": descriptor, "EDA_term": eda,
                "structure": n, "mechanism": model[n].get("mechanism", ""),
                "stereo": model[n].get("stereo", ""),
                "substrate_family": model[n].get("substrate_family", ""),
                "catalyst_family": model[n].get("catalyst_family", ""),
                "x_descriptor": x, "y_EDA": y, "fitted_y": fitted,
                "residual": y - fitted,
            }
            points.append(point_row)
            combined.append(point_row)
        safe = re.sub(r"[^A-Za-z0-9_.-]+", "_", f"{relationship_id}_{descriptor}__{eda}__{row['subset']}")
        filename = safe[:180] + ".csv"
        row["data_file"] = f"linear_relationship_tables/{filename}"
        write_rows(table_dir / filename, points, PLOT_DATA_FIELDS)
    write_rows(Path(outdir) / "selected_linear_plot_data.csv", combined, PLOT_DATA_FIELDS)


